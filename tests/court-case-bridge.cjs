const detail={status:200,data:{dma_csBasInf:{cortOfcCd:'B000210',csNo:'20080130025092'},
 dlt_dspslGdsDspslObjctLst:[{cortOfcCd:'B000210',csNo:'20080130025092',dspslGdsSeq:'1'}]}};
