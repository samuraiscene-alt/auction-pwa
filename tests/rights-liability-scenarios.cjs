'use strict';
const assert=require('node:assert/strict');
const {calculateLiabilityScenario:calc}=require('../scripts/rights-liability-scenarios.cjs');
const fees={acquisitionTaxWon:15000000,registrationWon:1000000,evictionWon:4000000,otherWon:0};
const known=calc({bidWon:350000000,assumedLiabilityWon:100000000,fees});
assert.equal(known.ok,true);
assert.equal(known.scenarioTotalWon,470000000);
assert.equal(known.totalConfirmed,false);
assert.equal(known.legalStatusVerified,false);
const missing=calc({bidWon:350000000,fees:{acquisitionTaxWon:15000000}});
assert.equal(missing.ok,true);
assert.equal(missing.scenarioTotalWon,null);
assert.equal(missing.partialWon,365000000);
assert(missing.missingFields.includes('assumedLiabilityWon'));
assert(missing.missingFields.includes('evictionWon'));
assert.equal(calc({bidWon:350000000,assumedLiabilityWon:-1,fees}).ok,false);
assert.equal(calc({bidWon:350000000,assumedLiabilityWon:'0',fees}).ok,false);
assert.equal(calc({bidWon:350000000,assumedLiabilityWon:100000000,fees:{...fees,evictionWon:'0'}}).ok,false);
assert.equal(calc({bidWon:350000000,assumedLiabilityWon:0,fees}).totalConfirmed,false);
assert.equal(calc({bidWon:350000000,assumedLiabilityWon:0,fees}).scenarioTotalWon,370000000);
console.log('PASS rights financial scenario arithmetic and unknown/assumed amount safeguards');
