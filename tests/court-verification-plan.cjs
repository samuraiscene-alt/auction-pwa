'use strict';
const assert=require('node:assert/strict');
const {buildPlan,koreaToday}=require('../scripts/build-court-verification-plan.cjs');
const {validateSnapshot}=require('../scripts/validate-capital-snapshot.cjs');
const fs=require('node:fs');
const live=JSON.parse(fs.readFileSync('data/capital-court-pilot.json','utf8'));
assert.equal(validateSnapshot(live,null,{strict:true}).ok,true);
const plan=buildPlan(live,'2026-11-10',7);
assert.equal(plan.snapshotItems,live.items.length);
assert.equal(plan.automaticCourtRequests,0);
assert.equal(plan.legalStatusVerified,false);
assert.equal(plan.partialCoverage,true);
assert.equal(plan.days.length,8);
const target=live.items.find(x=>x.saleDate);
const day=target.saleDate;
const onDay=buildPlan(live,day,7);
assert(onDay.days[0].sale_day.includes(target.id));
assert(onDay.days[1].result_check.includes(target.id));
assert(onDay.days[2].result_recheck.includes(target.id));
assert(onDay.days[3].result_recheck.includes(target.id));
assert(onDay.days[7].final_followup.includes(target.id));
const before=buildPlan(live,new Date(Date.parse(day+'T00:00:00Z')-86400000).toISOString().slice(0,10),0);
assert(before.days[0].precheck.includes(target.id));
assert.equal(koreaToday(new Date('2026-11-09T15:00:00.000Z')),'2026-11-10');
assert.throws(()=>buildPlan({...live,validation:{passed:false}},'2026-11-10'));
assert.throws(()=>buildPlan(live,'2026-02-29'));
assert.throws(()=>buildPlan(live,'2026-11-10',100));
const corrupted=structuredClone(live);corrupted.items[0].saleDate='2026-02-30';
assert.throws(()=>buildPlan(corrupted,'2026-11-10'));
console.log('PASS: date-driven plan, timezone, missing/invalid data and zero official requests');
