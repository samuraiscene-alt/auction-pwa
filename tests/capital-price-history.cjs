'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {updateHistory}=require('../scripts/record-capital-price-history.cjs');
const snapshot=JSON.parse(fs.readFileSync('data/capital-court-pilot.json','utf8'));
const prev=structuredClone(snapshot);
const cur=structuredClone(snapshot);
cur.fetchedAt=new Date(Date.parse(prev.fetchedAt)+60000).toISOString();
const original=prev.items.find(x=>x.minimumWon&&x.minimumWon>10000);
const target=cur.items.find(x=>x.id===original.id);
target.minimumWon=original.minimumWon-10000;
let result=updateHistory(prev,cur);
assert.equal(result.events.length,1);
assert.equal(result.events[0].id,original.id);
assert.equal(result.events[0].previousMinimumWon,original.minimumWon);
assert.equal(result.events[0].currentMinimumWon,target.minimumWon);
assert.equal(result.legalStatusVerified,false);
assert.equal(result.partialCoverage,true);
assert(!Object.hasOwn(result.events[0],'status'));
const again=updateHistory(prev,cur,result);
assert.equal(again.events.length,1,'same observation cannot duplicate');
const unchanged=structuredClone(cur);
unchanged.fetchedAt=new Date(Date.parse(cur.fetchedAt)+60000).toISOString();
assert.equal(updateHistory(cur,unchanged,again).events.length,1,'unchanged values must not add events');
assert.throws(()=>updateHistory(cur,prev),'backwards chronology must fail');
const corrupt=structuredClone(cur);corrupt.validation.passed=false;
assert.throws(()=>updateHistory(prev,corrupt),'unverified data must fail');
assert.throws(()=>updateHistory(prev,cur,{schemaVersion:1,kind:'observed_snapshot_prices',events:[{...result.events[0],currentMinimumWon:null}]}));
console.log('PASS: price observations only on verified changes; duplicate, invalid, stale and outcome inference protection');
